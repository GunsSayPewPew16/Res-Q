-- Res-Q · surplus_claims
--
-- A post used to be takeable once. The first recipient to click flipped
-- surplus_posts.status to 'claimed' and the item closed to everybody else, so two
-- organisations looking at the same pallet of bread could not both ask for it and
-- the donor never learned who else wanted it. A post now carries as many claims as
-- there are recipients who ask for it — the donor rations what they have between
-- them — and this is the table that holds those claims: one row per recipient per
-- post, each carrying who asked and when.
--
-- surplus_posts.status still settles to 'claimed' on the first claim, because that
-- is the board's own one-word state and what its chips read. What it no longer
-- means is *closed*: the feed keeps the claim action on a claimed post, and the card
-- above that action is what names the claimants —
--
--     Daniela Ruiz and 2 more claimed
--
-- which is read straight off this table by frontend/resq_supabase.js.
--
-- Run it in Supabase → SQL Editor → New query → Run, the way the two scripts before
-- it were run, or keep the project linked with the Supabase CLI and let
-- `supabase db push` apply it. It is written to be safe to run more than once.
--
--   psql "$DATABASE_URL" -f supabase/migrations/20261012000000_create_surplus_claims.sql


-- ---------------------------------------------------------------------------
-- Table
-- ---------------------------------------------------------------------------
-- id and claimed_at are generated by the database, so a page never has to invent
-- either. post_id points back at the post being claimed, and the row goes with the
-- post: deleting a post (nothing in the site does, but a person clearing the board
-- might) takes its claims with it rather than leaving them pointing at nothing.
--
-- recipient_name is the person who claimed it and recipient_org the organisation
-- they claimed it for, both as the profile carries them. Names are the board's own
-- coin: a post is filed under donor_name and a claim under recipient_name, compared
-- trimmed and case-insensitively, which is what the unique index below does.
create table if not exists public.surplus_claims (
    id             uuid primary key default gen_random_uuid(),
    post_id        uuid not null references public.surplus_posts (id) on delete cascade,
    recipient_name text not null,
    recipient_org  text,
    claimed_at     timestamptz not null default now()
);

-- Every read is "the claims on these posts", once per board draw.
create index if not exists surplus_claims_post_id_idx
    on public.surplus_claims (post_id);

-- One recipient claims one post once: clicking Claim twice, or two dashboards open
-- on the same account, cannot double-count a claimant. The index is on the folded
-- name for the same reason the pages fold one — "Daniela Ruiz " and "daniela ruiz"
-- are one recipient.
create unique index if not exists surplus_claims_one_per_recipient_idx
    on public.surplus_claims (post_id, lower(recipient_name));


-- ---------------------------------------------------------------------------
-- Row level security
-- ---------------------------------------------------------------------------
-- The pages hold only the publishable key, which is the anonymous role, and Res-Q
-- runs its own sign-in rather than Supabase Auth — so this table has to be readable
-- and writable by `anon`, exactly as surplus_posts is. RLS stays on with explicit
-- policies: the surface is "read the claims, add a claim", and nothing else. There
-- is no update and no delete policy on purpose, because a claim is a thing that
-- happened rather than a thing that is edited — a second click is refused by the
-- unique index above rather than rewriting the first claim.
alter table public.surplus_claims enable row level security;

drop policy if exists "surplus claims are public" on public.surplus_claims;
create policy "surplus claims are public"
    on public.surplus_claims for select
    to anon, authenticated
    using (true);

drop policy if exists "surplus claims accept new rows" on public.surplus_claims;
create policy "surplus claims accept new rows"
    on public.surplus_claims for insert
    to anon, authenticated
    with check (true);

-- Belt and braces, as on the posts table: the policies already gate every request,
-- but a role whose default privileges were changed elsewhere still needs the grant.
grant select, insert on public.surplus_claims to anon, authenticated;


-- ---------------------------------------------------------------------------
-- Realtime
-- ---------------------------------------------------------------------------
-- A claim is pushed to every open board over Supabase Realtime, which is what moves
-- a donor's "{first recipient} and N more claimed" line as somebody else claims the
-- same post. A table only streams once it is in the supabase_realtime publication,
-- and adding it twice is an error, so the join is made by hand. The pages also
-- re-read this table on a timer, so a project where this block was skipped still
-- shows the claims, just a little later. The block is guarded rather than trusting:
-- the whole script runs as one transaction in the SQL editor, so an error here would
-- roll the table back with it.
do $$
begin
    if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
        raise notice 'no supabase_realtime publication here: the boards will re-read the claims every 20 seconds instead';
    elsif not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'surplus_claims'
    ) then
        alter publication supabase_realtime add table public.surplus_claims;
    end if;
exception when others then
    raise notice 'the claims table was not added to supabase_realtime (%): the boards will re-read it every 20 seconds instead', sqlerrm;
end;
$$;


-- ---------------------------------------------------------------------------
-- Done
-- ---------------------------------------------------------------------------
-- The editor prints this one row when the whole script went through.
select 'surplus_claims is ready' as result;
